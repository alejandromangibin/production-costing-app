-- Ingredient inventory, part 4a (BRD INV-01 to INV-04, INV-08, INV-16, INV-17; design note
-- docs/inventory-data-design.md, section 1; decisions D-22, D-23, D-25).
-- Row-level security exactly as for the other business tables (002_multitenant.sql). The stock ledger and
-- the purchase-correction history are append-only: the app role can add lines but never delete them, and
-- on the ledger it can change only a purchase's supplier, reference and expiry date (INV-17).

-- At most one row per business. A missing row means inventory is not live yet.
CREATE TABLE business_settings (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  tenant_id integer NOT NULL DEFAULT NULLIF(current_setting('app.tenant_id', true), '')::int REFERENCES tenants (id),
  inventory_live_since date,
  live_set_by_user_id integer,
  live_set_by_name text,
  live_set_at timestamptz,
  CONSTRAINT business_settings_one_per_tenant UNIQUE (tenant_id),
  CONSTRAINT business_settings_tenant_id_key UNIQUE (tenant_id, id),
  -- The live date and who set it are all empty or all filled in.
  CONSTRAINT business_settings_live_set_together CHECK (
    (inventory_live_since IS NULL AND live_set_by_user_id IS NULL AND live_set_by_name IS NULL AND live_set_at IS NULL)
    OR (inventory_live_since IS NOT NULL AND live_set_by_user_id IS NOT NULL AND live_set_by_name IS NOT NULL
        AND live_set_by_name <> '' AND live_set_at IS NOT NULL)
  )
);

CREATE TABLE ingredients (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  tenant_id integer NOT NULL DEFAULT NULLIF(current_setting('app.tenant_id', true), '')::int REFERENCES tenants (id),
  name text NOT NULL CHECK (char_length(name) BETWEEN 1 AND 80),
  base_unit text NOT NULL CHECK (base_unit IN ('g', 'mL', 'pc')),
  -- Quantities are in thousandths of the base unit, the average in 1/10,000 centavo per base unit.
  low_stock_milli bigint CHECK (low_stock_milli BETWEEN 0 AND 10000000000),
  active boolean NOT NULL DEFAULT true,
  -- A copy of the ledger, kept for fast screens and safe saves. On hand may be below zero (INV-06).
  on_hand_milli bigint NOT NULL DEFAULT 0,
  avg_cost_e4 bigint CHECK (avg_cost_e4 BETWEEN 0 AND 1000000000000),
  -- Goes up by 1 every time the average changes: the "prices changed" check at Save.
  avg_version integer NOT NULL DEFAULT 0,
  -- The person's id and name are saved on the row: the app role cannot read the users table (D-25).
  created_by_user_id integer NOT NULL,
  created_by_name text NOT NULL CHECK (created_by_name <> ''),
  created_at timestamptz NOT NULL DEFAULT now(),
  CONSTRAINT ingredients_tenant_id_key UNIQUE (tenant_id, id)
);
CREATE UNIQUE INDEX ingredients_tenant_name_key ON ingredients (tenant_id, lower(name));

-- A ledger line can point at the run line it belongs to, inside the same run and business.
ALTER TABLE run_costs ADD CONSTRAINT run_costs_tenant_run_id_key UNIQUE (tenant_id, run_id, id);

-- The stock ledger: facts only, never running totals, because a back-dated line changes them.
CREATE TABLE stock_movements (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  tenant_id integer NOT NULL DEFAULT NULLIF(current_setting('app.tenant_id', true), '')::int REFERENCES tenants (id),
  ingredient_id integer NOT NULL,
  kind text NOT NULL CHECK (kind IN ('opening', 'purchase', 'purchase_reversal', 'run_use', 'void_return', 'spillage', 'spoilage', 'count_correction')),
  effective_date date NOT NULL,
  -- Signed change in on hand.
  quantity_milli bigint NOT NULL CHECK (quantity_milli BETWEEN -10000000000 AND 10000000000),
  total_cost_cents integer CHECK (total_cost_cents BETWEEN 0 AND 2000000000),
  supplier text NOT NULL DEFAULT '' CHECK (char_length(supplier) <= 120),
  reference text NOT NULL DEFAULT '' CHECK (char_length(reference) <= 120),
  expiry_date date,
  reason text NOT NULL DEFAULT '' CHECK (char_length(reason) <= 300),
  run_id integer,
  run_cost_id integer,
  -- The average a run line used (BR-20).
  unit_cost_e4 bigint CHECK (unit_cost_e4 BETWEEN 0 AND 1000000000000),
  reverses_movement_id integer,
  entered_by_user_id integer NOT NULL,
  entered_by_name text NOT NULL CHECK (entered_by_name <> ''),
  entered_at timestamptz NOT NULL DEFAULT now(),
  CONSTRAINT stock_movements_tenant_id_key UNIQUE (tenant_id, id),
  CONSTRAINT stock_movements_tenant_ingredient_id_key UNIQUE (tenant_id, ingredient_id, id),
  -- Every link stays inside the business. A reversal can only point at a line of the same ingredient.
  CONSTRAINT stock_movements_same_tenant_ingredient FOREIGN KEY (tenant_id, ingredient_id) REFERENCES ingredients (tenant_id, id),
  CONSTRAINT stock_movements_same_tenant_run FOREIGN KEY (tenant_id, run_id) REFERENCES runs (tenant_id, id),
  CONSTRAINT stock_movements_same_run_cost FOREIGN KEY (tenant_id, run_id, run_cost_id) REFERENCES run_costs (tenant_id, run_id, id),
  CONSTRAINT stock_movements_same_ingredient_reversal FOREIGN KEY (tenant_id, ingredient_id, reverses_movement_id) REFERENCES stock_movements (tenant_id, ingredient_id, id),
  -- What each kind of line must and must not hold (design note 1.4).
  CONSTRAINT stock_movements_quantity_by_kind CHECK (
    (kind IN ('opening', 'purchase') AND quantity_milli > 0)
    OR (kind IN ('purchase_reversal', 'spillage', 'spoilage') AND quantity_milli < 0)
    OR (kind = 'run_use' AND quantity_milli <= 0)
    OR (kind = 'void_return' AND quantity_milli >= 0)
    OR (kind = 'count_correction' AND quantity_milli <> 0)
  ),
  CONSTRAINT stock_movements_cost_by_kind CHECK ((total_cost_cents IS NOT NULL) = (kind IN ('opening', 'purchase'))),
  CONSTRAINT stock_movements_details_by_kind CHECK (kind = 'purchase' OR (supplier = '' AND reference = '' AND expiry_date IS NULL)),
  CONSTRAINT stock_movements_reason_by_kind CHECK (
    kind NOT IN ('opening', 'purchase_reversal', 'spillage', 'spoilage', 'count_correction') OR btrim(reason) <> ''
  ),
  CONSTRAINT stock_movements_run_by_kind CHECK ((run_id IS NOT NULL) = (kind IN ('run_use', 'void_return'))),
  CONSTRAINT stock_movements_run_cost_by_kind CHECK ((run_cost_id IS NOT NULL) = (kind IN ('run_use', 'void_return'))),
  CONSTRAINT stock_movements_unit_cost_by_kind CHECK ((unit_cost_e4 IS NOT NULL) = (kind = 'run_use')),
  CONSTRAINT stock_movements_reversal_by_kind CHECK ((reverses_movement_id IS NOT NULL) = (kind = 'purchase_reversal')),
  CONSTRAINT stock_movements_not_own_reversal CHECK (reverses_movement_id <> id),
  -- At most P1,000,000 per base unit, written so it stays in whole numbers.
  CONSTRAINT stock_movements_unit_price_limit CHECK (total_cost_cents <= 100000 * quantity_milli)
);
CREATE INDEX stock_movements_replay_idx ON stock_movements (ingredient_id, effective_date, id);
CREATE INDEX stock_movements_run_idx ON stock_movements (run_id);
-- A line is reversed at most once, and one run line is used and returned at most once.
CREATE UNIQUE INDEX stock_movements_reversed_once ON stock_movements (reverses_movement_id);
CREATE UNIQUE INDEX stock_movements_run_use_once ON stock_movements (run_cost_id) WHERE kind = 'run_use';
CREATE UNIQUE INDEX stock_movements_void_return_once ON stock_movements (run_cost_id) WHERE kind = 'void_return';

-- One row each time the owner corrects a purchase's details (INV-17), with the values before the change.
CREATE TABLE purchase_detail_changes (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  tenant_id integer NOT NULL DEFAULT NULLIF(current_setting('app.tenant_id', true), '')::int REFERENCES tenants (id),
  movement_id integer NOT NULL,
  supplier text NOT NULL CHECK (char_length(supplier) <= 120),
  reference text NOT NULL CHECK (char_length(reference) <= 120),
  expiry_date date,
  changed_by_user_id integer NOT NULL,
  changed_by_name text NOT NULL CHECK (changed_by_name <> ''),
  changed_at timestamptz NOT NULL DEFAULT now(),
  CONSTRAINT purchase_detail_changes_tenant_id_key UNIQUE (tenant_id, id),
  CONSTRAINT purchase_detail_changes_same_tenant_movement FOREIGN KEY (tenant_id, movement_id) REFERENCES stock_movements (tenant_id, id)
);
CREATE INDEX purchase_detail_changes_movement_idx ON purchase_detail_changes (movement_id);

ALTER TABLE business_settings ENABLE ROW LEVEL SECURITY;
ALTER TABLE ingredients ENABLE ROW LEVEL SECURITY;
ALTER TABLE stock_movements ENABLE ROW LEVEL SECURITY;
ALTER TABLE purchase_detail_changes ENABLE ROW LEVEL SECURITY;

CREATE POLICY tenant_isolation ON business_settings
  USING (tenant_id = NULLIF(current_setting('app.tenant_id', true), '')::int)
  WITH CHECK (tenant_id = NULLIF(current_setting('app.tenant_id', true), '')::int);
CREATE POLICY tenant_isolation ON ingredients
  USING (tenant_id = NULLIF(current_setting('app.tenant_id', true), '')::int)
  WITH CHECK (tenant_id = NULLIF(current_setting('app.tenant_id', true), '')::int);
CREATE POLICY tenant_isolation ON stock_movements
  USING (tenant_id = NULLIF(current_setting('app.tenant_id', true), '')::int)
  WITH CHECK (tenant_id = NULLIF(current_setting('app.tenant_id', true), '')::int);
CREATE POLICY tenant_isolation ON purchase_detail_changes
  USING (tenant_id = NULLIF(current_setting('app.tenant_id', true), '')::int)
  WITH CHECK (tenant_id = NULLIF(current_setting('app.tenant_id', true), '')::int);

GRANT SELECT, INSERT, UPDATE ON business_settings, ingredients TO costing_app;
-- Add only, except a purchase's correctable details. No DELETE.
GRANT SELECT, INSERT ON stock_movements TO costing_app;
GRANT UPDATE (supplier, reference, expiry_date) ON stock_movements TO costing_app;
-- Read and add only.
GRANT SELECT, INSERT ON purchase_detail_changes TO costing_app;
GRANT USAGE, SELECT ON SEQUENCE business_settings_id_seq, ingredients_id_seq, stock_movements_id_seq, purchase_detail_changes_id_seq TO costing_app;
