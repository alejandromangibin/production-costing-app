-- Production Costing App: initial schema.
-- Money is stored as whole centavos (integer). Dates are real DATE columns.

CREATE TABLE products (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  code text NOT NULL UNIQUE,
  name text NOT NULL,
  shelf_life_days integer NOT NULL CHECK (shelf_life_days >= 0),
  notes text NOT NULL DEFAULT '',
  active boolean NOT NULL DEFAULT true,
  created_at timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE pack_sizes (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  product_id integer NOT NULL REFERENCES products (id),
  pieces_per_pack integer NOT NULL CHECK (pieces_per_pack >= 1),
  retail_price_cents integer NOT NULL CHECK (retail_price_cents > 0),
  reseller_price_cents integer CHECK (reseller_price_cents IS NULL OR reseller_price_cents > 0),
  packaging_cost_cents integer NOT NULL DEFAULT 0 CHECK (packaging_cost_cents >= 0),
  is_default boolean NOT NULL DEFAULT false,
  active boolean NOT NULL DEFAULT true,
  UNIQUE (product_id, pieces_per_pack)
);

-- At most one active default pack size per product.
CREATE UNIQUE INDEX pack_sizes_one_default ON pack_sizes (product_id) WHERE is_default AND active;

CREATE TABLE runs (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  run_date date NOT NULL,
  note text NOT NULL DEFAULT '',
  status text NOT NULL DEFAULT 'saved' CHECK (status IN ('saved', 'void')),
  void_reason text,
  voided_at timestamptz,
  total_cost_cents integer NOT NULL CHECK (total_cost_cents >= 0),
  created_at timestamptz NOT NULL DEFAULT now()
);

CREATE INDEX runs_run_date_idx ON runs (run_date);

-- One product inside a run. Names and results are snapshots.
CREATE TABLE run_products (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  run_id integer NOT NULL REFERENCES runs (id),
  product_id integer NOT NULL REFERENCES products (id),
  product_code text NOT NULL,
  product_name text NOT NULL,
  loose_pieces integer NOT NULL CHECK (loose_pieces >= 0),
  rejected_pieces integer NOT NULL CHECK (rejected_pieces >= 0),
  packed_pieces integer NOT NULL CHECK (packed_pieces >= 0),
  pieces_made integer NOT NULL CHECK (pieces_made > 0),
  good_pieces integer NOT NULL CHECK (good_pieces > 0),
  shared_share_cents integer NOT NULL CHECK (shared_share_cents >= 0),
  specific_cents integer NOT NULL CHECK (specific_cents >= 0),
  packaging_cents integer NOT NULL CHECK (packaging_cents >= 0),
  total_cost_cents integer NOT NULL CHECK (total_cost_cents >= 0),
  -- Derived value: centavos per good piece, before packaging.
  cost_per_good_piece double precision NOT NULL,
  batch_code text NOT NULL UNIQUE,
  production_date date NOT NULL,
  expiry_date date NOT NULL,
  CHECK (expiry_date >= production_date),
  UNIQUE (run_id, product_id)
);

CREATE INDEX run_products_product_idx ON run_products (product_id);
CREATE INDEX run_products_expiry_idx ON run_products (expiry_date);

-- Packs of one size made in a run (only sizes with at least one pack).
CREATE TABLE run_packings (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  run_product_id integer NOT NULL REFERENCES run_products (id),
  pack_size_id integer NOT NULL REFERENCES pack_sizes (id),
  pieces_per_pack integer NOT NULL CHECK (pieces_per_pack >= 1),
  retail_price_cents integer NOT NULL CHECK (retail_price_cents > 0),
  packaging_cost_cents integer NOT NULL CHECK (packaging_cost_cents >= 0),
  packs integer NOT NULL CHECK (packs > 0),
  pack_cost_cents integer NOT NULL CHECK (pack_cost_cents >= 0),
  margin_pct double precision NOT NULL,
  markup_pct double precision
);

CREATE INDEX run_packings_run_product_idx ON run_packings (run_product_id);

CREATE TABLE run_costs (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  run_id integer NOT NULL REFERENCES runs (id),
  category text NOT NULL CHECK (category IN ('ingredient', 'gas', 'electricity', 'labor', 'other')),
  description text NOT NULL DEFAULT '',
  amount_cents integer NOT NULL CHECK (amount_cents >= 0),
  scope text NOT NULL CHECK (scope IN ('shared', 'specific'))
);

CREATE INDEX run_costs_run_idx ON run_costs (run_id);

-- Which products a specific cost line is charged to.
CREATE TABLE run_cost_targets (
  run_cost_id integer NOT NULL REFERENCES run_costs (id),
  run_product_id integer NOT NULL REFERENCES run_products (id),
  PRIMARY KEY (run_cost_id, run_product_id)
);
