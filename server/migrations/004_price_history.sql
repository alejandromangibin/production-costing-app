-- Price history (requirement RUN-10 / Q16, decisions D-08, D-23, D-25): one row each time a pack size's
-- prices or settings change, with the values after the change and who made it.
-- Row-level security exactly as for the other business tables (002_multitenant.sql). The app role may
-- only read and add rows: history is never changed or deleted (append-only, like the stock ledger in D-23).

CREATE TABLE pack_size_changes (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  tenant_id integer NOT NULL DEFAULT NULLIF(current_setting('app.tenant_id', true), '')::int REFERENCES tenants (id),
  pack_size_id integer NOT NULL,
  kind text NOT NULL CHECK (kind IN ('created', 'updated')),
  -- Values after the change.
  retail_price_cents integer NOT NULL CHECK (retail_price_cents > 0),
  reseller_price_cents integer CHECK (reseller_price_cents IS NULL OR reseller_price_cents > 0),
  packaging_cost_cents integer NOT NULL CHECK (packaging_cost_cents >= 0),
  is_default boolean NOT NULL,
  active boolean NOT NULL,
  -- The person's id and name are saved on the row: the app role cannot read the users table (D-25).
  changed_by_user_id integer,
  changed_by_name text NOT NULL DEFAULT '',
  changed_at timestamptz NOT NULL DEFAULT now(),
  -- A change can only belong to a pack size of the same business.
  CONSTRAINT pack_size_changes_same_tenant_pack_size FOREIGN KEY (tenant_id, pack_size_id) REFERENCES pack_sizes (tenant_id, id)
);
CREATE INDEX pack_size_changes_pack_size_idx ON pack_size_changes (pack_size_id, changed_at);

ALTER TABLE pack_size_changes ENABLE ROW LEVEL SECURITY;
CREATE POLICY tenant_isolation ON pack_size_changes
  USING (tenant_id = NULLIF(current_setting('app.tenant_id', true), '')::int)
  WITH CHECK (tenant_id = NULLIF(current_setting('app.tenant_id', true), '')::int);

-- Read and add only: no UPDATE, no DELETE.
GRANT SELECT, INSERT ON pack_size_changes TO costing_app;
GRANT USAGE, SELECT ON SEQUENCE pack_size_changes_id_seq TO costing_app;
