-- ---------------------------------------------------------------------------
-- Row-level security
-- ---------------------------------------------------------------------------
-- The server runs every business request as the low-privilege role costing_app, with
-- app.tenant_id set to the logged-in business. The policies then hide every other business's rows.
-- The account tables above (tenants, users, sessions, payments) are NOT granted to costing_app at all.

DO $$
BEGIN
  IF NOT EXISTS (SELECT 1 FROM pg_roles WHERE rolname = 'costing_app') THEN
    CREATE ROLE costing_app NOLOGIN;
  END IF;
END $$;

-- The database user must be allowed to switch to that role. (On PostgreSQL 16 the creator of a role
-- does not get that automatically, so this grant is always needed.) If the user lacks the right to
-- grant it, carry on: the server's startup check then stops with a clear message instead.
DO $$
BEGIN
  GRANT costing_app TO CURRENT_USER;
EXCEPTION WHEN insufficient_privilege THEN
  RAISE NOTICE 'Could not grant costing_app to %: %', current_user, SQLERRM;
END $$;
-- Some hosts (and recreated schemas) do not give everyone access to the public schema by default.
GRANT USAGE ON SCHEMA public TO costing_app;

