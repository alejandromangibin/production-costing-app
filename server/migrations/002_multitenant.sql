-- Multi-client version: businesses (tenants), people who log in, sessions, payments, and
-- row-level security so one business can never see another business's data.

-- ---------------------------------------------------------------------------
-- Accounts
-- ---------------------------------------------------------------------------

CREATE TABLE tenants (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name text NOT NULL,
  -- Stored status. What the business may actually do today is worked out from this and the dates.
  status text NOT NULL DEFAULT 'trial' CHECK (status IN ('trial', 'active', 'cancelled', 'suspended')),
  trial_ends_on date NOT NULL,
  paid_through date,
  notes text NOT NULL DEFAULT '',
  created_at timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE users (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  tenant_id integer REFERENCES tenants (id),
  email text NOT NULL,
  name text NOT NULL DEFAULT '',
  role text NOT NULL CHECK (role IN ('owner', 'staff', 'platform_admin')),
  -- Null until the person accepts their invite and chooses a password.
  password_hash text,
  active boolean NOT NULL DEFAULT true,
  created_at timestamptz NOT NULL DEFAULT now(),
  last_login_at timestamptz,
  -- Only the platform admin (you) has no business.
  CHECK ((role = 'platform_admin') = (tenant_id IS NULL))
);

CREATE UNIQUE INDEX users_email_unique ON users (lower(email));
CREATE UNIQUE INDEX users_one_owner_per_tenant ON users (tenant_id) WHERE role = 'owner';

-- The session id is stored hashed, so a database leak does not hand out working logins.
CREATE TABLE sessions (
  id text PRIMARY KEY,
  user_id integer NOT NULL REFERENCES users (id) ON DELETE CASCADE,
  created_at timestamptz NOT NULL DEFAULT now(),
  expires_at timestamptz NOT NULL,
  last_seen_at timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX sessions_user_idx ON sessions (user_id);

-- One-time links for choosing a first password (invite) or a new one (reset). Stored hashed.
CREATE TABLE user_tokens (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id integer NOT NULL REFERENCES users (id) ON DELETE CASCADE,
  kind text NOT NULL CHECK (kind IN ('invite', 'reset')),
  token_hash text NOT NULL UNIQUE,
  expires_at timestamptz NOT NULL,
  used_at timestamptz,
  created_at timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX user_tokens_user_idx ON user_tokens (user_id);

-- Payments you record by hand (GCash, bank transfer, cash). Each one extends paid_through.
CREATE TABLE payments (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  tenant_id integer NOT NULL REFERENCES tenants (id),
  amount_cents integer NOT NULL CHECK (amount_cents >= 0),
  method text NOT NULL DEFAULT '',
  reference text NOT NULL DEFAULT '',
  paid_on date NOT NULL,
  months integer NOT NULL CHECK (months BETWEEN 1 AND 36),
  note text NOT NULL DEFAULT '',
  recorded_by integer REFERENCES users (id),
  created_at timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX payments_tenant_idx ON payments (tenant_id);

